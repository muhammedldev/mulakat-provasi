export function buildGameQuestions(
  seed: string = createSeed(),
  sector?: SectorId
): { questions: Question[]; seed: string } {
  const rng = rngFromSeed(seed);
  const result: Question[] = [];
  interviewers.forEach((interviewer) => {
    const pool = questionPool.filter((q) => q.interviewerId === interviewer.id);
    // Bir sektör seçildiyse, o sektöre özel sorular (varsa) önce yerleştirilir,
    // kalan slotlar her zamanki gibi genel havuzdan dolduruluyor — bu yüzden
    // toplam soru sayısı (18) ve zorluk dağılımı sektör seçilse de seçilmese
    // de tamamen aynı kalıyor.
    const sectorPool = sector
      ? sectorQuestionPool.filter((q) => q.interviewerId === interviewer.id && q.sector === sector)
      : [];
    const pick = (difficulty: Difficulty, n: number) => {
      const sectorMatches = shuffleSeeded(sectorPool.filter((q) => q.difficulty === difficulty), rng).slice(0, n);
      const remaining = n - sectorMatches.length;
      const genericMatches = shuffleSeeded(pool.filter((q) => q.difficulty === difficulty), rng).slice(0, remaining);
      return [...sectorMatches, ...genericMatches];
    };
    result.push(...pick("kolay", 2), ...pick("orta", 2), ...pick("zor", 1), ...pick("efsane", 1));
  });
  // Picking WHICH questions appear doesn't randomize each question's own
  // answer order — without this, the correct option sits at whatever position
  // it was authored at (measured: ~85% longest-text, ~55% first slot), making
  // the quiz gameable by pattern rather than knowledge.
  const withShuffledOptions = result.map((q) => ({ ...q, options: shuffleSeeded(q.options, rng) }));
  return { questions: withShuffledOptions, seed };
}
